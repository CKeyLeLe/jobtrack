CREATE TABLE job_applications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Chaque candidature appartient à un utilisateur ; supprimer l'utilisateur supprime ses candidatures.
    user_id      BIGINT                   NOT NULL,
    company      VARCHAR(150)             NOT NULL,
    job_title    VARCHAR(150)             NOT NULL,
    status       VARCHAR(20)              NOT NULL,
    applied_on   DATE                     NOT NULL,
    follow_up_on DATE,
    notes        VARCHAR(2000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_job_applications_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    -- Dernier rempart si une valeur invalide échappait à la validation Java.
    CONSTRAINT ck_job_applications_status
        CHECK (status IN ('APPLIED', 'INTERVIEW', 'OFFER', 'REJECTED', 'WITHDRAWN'))
);

-- Index alignés sur les requêtes prévues : liste filtrée par statut et liste des relances.
CREATE INDEX idx_job_applications_user_status ON job_applications (user_id, status);
CREATE INDEX idx_job_applications_user_follow_up ON job_applications (user_id, follow_up_on);
